package StringsInJava;

public class OtherFunctionsInStrings {
    public static void main(String[] args) {
        //charAT
        String name = "Prabesh";
        int length = name.length();
        for(int i = 0; i <length; i++){
            System.out.println(name.charAt(i));
        }
    }
    
}
